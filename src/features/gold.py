def safe_divide(numerator: Column, denominator: Column) -> Column:
    """Safe division returning NULL when denominator is NULL, 0, or NaN."""
    return F.when(
        (denominator.isNotNull()) & (denominator != 0) & (~F.isnan(denominator)),
        numerator / denominator,
    ).otherwise(None)


