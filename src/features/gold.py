# 7. Multi-Table Assembly & Join Auditing
# ======================================================================

def join_features_to_spine(
    spine_df: DataFrame,
    feature_tables: list[tuple[str, DataFrame]],
    spine_name: str = "application_train",
) -> tuple[DataFrame, list[dict[str, Any]]]:
    """Sequentially left-join applicant-level feature DataFrames onto application spine.

    Strictly enforces zero row explosion (output rows == spine rows).
    """
    current_df = spine_df
    current_rows = current_df.count()
    expected_rows = current_rows

    join_audit: list[dict[str, Any]] = []

    logger.info(f"[{spine_name}] Starting assembly from spine ({expected_rows:,} rows)...")

    for feat_name, feat_df in feature_tables:
        t_start = time.time()
        right_rows = feat_df.count()

        # Execute left join
        joined_df = current_df.join(feat_df, on="SK_ID_CURR", how="left")
        output_rows = joined_df.count()

        row_increase = output_rows - current_rows
        is_pass = (row_increase == 0) and (output_rows == expected_rows)

        audit_entry = {
            "join": f"{spine_name} + {feat_name}",
            "spine": spine_name,
            "feature_table": feat_name,
            "join_key": "SK_ID_CURR",
            "left_rows": current_rows,
            "right_rows": right_rows,
            "output_rows": output_rows,
            "row_increase": row_increase,
            "duration_seconds": round(time.time() - t_start, 2),
            "status": "PASS" if is_pass else "FAIL",
        }
        join_audit.append(audit_entry)

        if not is_pass:
            raise AssertionError(
                f"FATAL: Join row explosion detected! {spine_name} + {feat_name} produced "
                f"{output_rows:,} rows (expected {expected_rows:,}, increase={row_increase:,})"
            )

        logger.info(
            f"[{spine_name}] Joined {feat_name}: {output_rows:,} rows (increase=0) in {audit_entry['duration_seconds']}s"
        )
        current_df = joined_df
        current_rows = output_rows

    return current_df, join_audit


def validate_gold_df(
    gold_df: DataFrame,
    expected_rows: int,
    is_train: bool = True,
) -> tuple[bool, list[str]]:
    """Validate Gold dataset completeness, uniqueness, absence of Inf/NaN, and column integrity."""
    errors = []
    actual_rows = gold_df.count()

    # 1. Row count
    if actual_rows != expected_rows:
        errors.append(f"Row count mismatch: expected {expected_rows:,}, got {actual_rows:,}")

    # 2. Key uniqueness
    distinct_keys = gold_df.select("SK_ID_CURR").distinct().count()
    if distinct_keys != actual_rows:
        errors.append(f"SK_ID_CURR is not unique: {distinct_keys:,} distinct vs {actual_rows:,} total")

    # 3. Column duplicates
    cols = gold_df.columns
    if len(cols) != len(set(cols)):
        duplicates = [c for c in set(cols) if cols.count(c) > 1]
        errors.append(f"Duplicate columns detected: {duplicates}")

    # 4. Target presence / absence
    if is_train:
        if "TARGET" not in cols:
            errors.append("TARGET column missing in training Gold dataset")
    else:
        if "TARGET" in cols:
            errors.append("TARGET column illegally present in inference Gold dataset")

    is_valid = len(errors) == 0
    return is_valid, errors


