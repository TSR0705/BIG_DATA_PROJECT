def aggregate_bureau_balance(df_bb: DataFrame) -> DataFrame:
    """Aggregate bureau_balance from (SK_ID_BUREAU, MONTHS_BALANCE) grain to SK_ID_BUREAU grain."""
    return df_bb.groupBy("SK_ID_BUREAU").agg(
        F.count("*").alias("BURO_BAL_MONTH_COUNT"),
        F.min("MONTHS_BALANCE").alias("BURO_BAL_MONTHS_MIN"),
        F.max("MONTHS_BALANCE").alias("BURO_BAL_MONTHS_MAX"),
        F.sum(F.when(F.col("STATUS") == "0", 1).otherwise(0)).alias("BURO_BAL_STATUS_0_COUNT"),
        F.sum(F.when(F.col("STATUS") == "1", 1).otherwise(0)).alias("BURO_BAL_STATUS_1_COUNT"),
        F.sum(F.when(F.col("STATUS") == "2", 1).otherwise(0)).alias("BURO_BAL_STATUS_2_COUNT"),
        F.sum(F.when(F.col("STATUS") == "3", 1).otherwise(0)).alias("BURO_BAL_STATUS_3_COUNT"),
        F.sum(F.when(F.col("STATUS") == "4", 1).otherwise(0)).alias("BURO_BAL_STATUS_4_COUNT"),
        F.sum(F.when(F.col("STATUS") == "5", 1).otherwise(0)).alias("BURO_BAL_STATUS_5_COUNT"),
        F.sum(F.when(F.col("STATUS") == "C", 1).otherwise(0)).alias("BURO_BAL_STATUS_C_COUNT"),
        F.sum(F.when(F.col("STATUS") == "X", 1).otherwise(0)).alias("BURO_BAL_STATUS_X_COUNT"),
        F.sum(F.when(F.col("STATUS").isin("1", "2", "3", "4", "5"), 1).otherwise(0)).alias("BURO_BAL_DPD_COUNT"),
    ).withColumn(
        "BURO_BAL_DPD_RATIO",
        safe_divide(F.col("BURO_BAL_DPD_COUNT"), F.col("BURO_BAL_MONTH_COUNT")),
    )


def aggregate_bureau(df_bureau: DataFrame, df_bb_agg: DataFrame | None = None) -> DataFrame:
    """Join bureau_balance aggregates onto bureau and aggregate to SK_ID_CURR grain."""
    if df_bb_agg is not None:
        bureau_joined = df_bureau.join(df_bb_agg, on="SK_ID_BUREAU", how="left")
    else:
        bureau_joined = df_bureau

    agg_exprs = [
        F.count("SK_ID_BUREAU").alias("BURO_RECORD_COUNT"),
        F.sum(F.when(F.col("CREDIT_ACTIVE") == "Active", 1).otherwise(0)).alias("BURO_ACTIVE_COUNT"),
        F.sum(F.when(F.col("CREDIT_ACTIVE") == "Closed", 1).otherwise(0)).alias("BURO_CLOSED_COUNT"),
        F.min("DAYS_CREDIT").alias("BURO_DAYS_CREDIT_MIN"),
        F.max("DAYS_CREDIT").alias("BURO_DAYS_CREDIT_MAX"),
        F.mean("DAYS_CREDIT").alias("BURO_DAYS_CREDIT_MEAN"),
        F.max("DAYS_CREDIT_ENDDATE").alias("BURO_DAYS_CREDIT_ENDDATE_MAX"),
        F.sum("AMT_CREDIT_SUM").alias("BURO_AMT_CREDIT_SUM_SUM"),
        F.mean("AMT_CREDIT_SUM").alias("BURO_AMT_CREDIT_SUM_MEAN"),
        F.max("AMT_CREDIT_SUM").alias("BURO_AMT_CREDIT_SUM_MAX"),
        F.sum("AMT_CREDIT_SUM_DEBT").alias("BURO_AMT_CREDIT_SUM_DEBT_SUM"),
        F.mean("AMT_CREDIT_SUM_DEBT").alias("BURO_AMT_CREDIT_SUM_DEBT_MEAN"),
        F.sum("AMT_CREDIT_SUM_OVERDUE").alias("BURO_AMT_CREDIT_SUM_OVERDUE_SUM"),
        F.max("AMT_CREDIT_SUM_OVERDUE").alias("BURO_AMT_CREDIT_SUM_OVERDUE_MAX"),
        F.sum("CNT_CREDIT_PROLONG").alias("BURO_CNT_CREDIT_PROLONG_SUM"),
        F.sum("AMT_ANNUITY").alias("BURO_AMT_ANNUITY_SUM"),
        F.mean("AMT_ANNUITY").alias("BURO_AMT_ANNUITY_MEAN"),
    ]

    if df_bb_agg is not None:
        agg_exprs.extend([
            F.sum("BURO_BAL_MONTH_COUNT").alias("BURO_BAL_MONTH_COUNT_SUM"),
            F.mean("BURO_BAL_MONTH_COUNT").alias("BURO_BAL_MONTH_COUNT_MEAN"),
            F.sum("BURO_BAL_DPD_COUNT").alias("BURO_BAL_DPD_COUNT_SUM"),
            F.mean("BURO_BAL_DPD_RATIO").alias("BURO_BAL_DPD_RATIO_MEAN"),
            F.sum("BURO_BAL_STATUS_0_COUNT").alias("BURO_BAL_STATUS_0_SUM"),
            F.sum("BURO_BAL_STATUS_C_COUNT").alias("BURO_BAL_STATUS_C_SUM"),
        ])

    bureau_curr = bureau_joined.groupBy("SK_ID_CURR").agg(*agg_exprs)

    # Derived ratios
    bureau_curr = bureau_curr.withColumn(
        "BURO_ACTIVE_RATIO",
        safe_divide(F.col("BURO_ACTIVE_COUNT"), F.col("BURO_RECORD_COUNT")),
    ).withColumn(
        "BURO_DEBT_TO_CREDIT_RATIO",
        safe_divide(F.col("BURO_AMT_CREDIT_SUM_DEBT_SUM"), F.col("BURO_AMT_CREDIT_SUM_SUM")),
    ).withColumn(
        "BURO_OVERDUE_TO_CREDIT_RATIO",
        safe_divide(F.col("BURO_AMT_CREDIT_SUM_OVERDUE_SUM"), F.col("BURO_AMT_CREDIT_SUM_SUM")),
    )

    return bureau_curr


