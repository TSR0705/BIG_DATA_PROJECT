        F.max("AMT_CREDIT_LIMIT_ACTUAL").alias("CC_AMT_CREDIT_LIMIT_MAX"),
        F.sum("AMT_DRAWINGS_ATM_CURRENT").alias("CC_AMT_DRAWINGS_ATM_SUM"),
        F.sum("AMT_DRAWINGS_CURRENT").alias("CC_AMT_DRAWINGS_CURRENT_SUM"),
        F.max("AMT_DRAWINGS_CURRENT").alias("CC_AMT_DRAWINGS_CURRENT_MAX"),
        F.sum("CNT_DRAWINGS_CURRENT").alias("CC_CNT_DRAWINGS_CURRENT_SUM"),
        F.mean("CNT_DRAWINGS_CURRENT").alias("CC_CNT_DRAWINGS_CURRENT_MEAN"),
