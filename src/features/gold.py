def build_app_features(df_app: DataFrame, is_train: bool = True) -> DataFrame:
    """Enhance application table with engineered financial and demographic ratios.

    Preserves SK_ID_CURR, TARGET (if train), all Silver columns, and adds APP_ ratios.
    """
    # Safe ratios
    df = df_app.withColumn(
        "APP_CREDIT_TO_INCOME_RATIO",
        safe_divide(F.col("AMT_CREDIT"), F.col("AMT_INCOME_TOTAL")),
    ).withColumn(
        "APP_ANNUITY_TO_INCOME_RATIO",
        safe_divide(F.col("AMT_ANNUITY"), F.col("AMT_INCOME_TOTAL")),
    ).withColumn(
        "APP_PAYMENT_RATE",
        safe_divide(F.col("AMT_ANNUITY"), F.col("AMT_CREDIT")),
    ).withColumn(
        "APP_GOODS_TO_CREDIT_RATIO",
        safe_divide(F.col("AMT_GOODS_PRICE"), F.col("AMT_CREDIT")),
    ).withColumn(
        "APP_INCOME_PER_FAMILY_MEMBER",
        safe_divide(F.col("AMT_INCOME_TOTAL"), F.col("CNT_FAM_MEMBERS")),
    )

    # Days-based ratios (DAYS_EMPLOYED and DAYS_BIRTH are negative offsets)
    df = df.withColumn(
        "APP_AGE_YEARS",
        F.abs(F.col("DAYS_BIRTH")) / 365.25,
    ).withColumn(
        "APP_EMPLOYED_YEARS",
        F.when(F.col("DAYS_EMPLOYED").isNotNull(), F.abs(F.col("DAYS_EMPLOYED")) / 365.25).otherwise(None),
    ).withColumn(
        "APP_DAYS_EMPLOYED_TO_BIRTH_RATIO",
        safe_divide(F.abs(F.col("DAYS_EMPLOYED")), F.abs(F.col("DAYS_BIRTH"))),
    ).withColumn(
        "APP_INCOME_TO_EMPLOYED_RATIO",
        safe_divide(F.col("AMT_INCOME_TOTAL"), F.abs(F.col("DAYS_EMPLOYED"))),
    )

    # External source aggregations
    df = df.withColumn(
        "APP_EXT_SOURCES_MEAN",
        (F.coalesce(F.col("EXT_SOURCE_1"), F.lit(0.0)) +
         F.coalesce(F.col("EXT_SOURCE_2"), F.lit(0.0)) +
         F.coalesce(F.col("EXT_SOURCE_3"), F.lit(0.0))) /
        (F.when(F.col("EXT_SOURCE_1").isNotNull(), 1).otherwise(0) +
         F.when(F.col("EXT_SOURCE_2").isNotNull(), 1).otherwise(0) +
         F.when(F.col("EXT_SOURCE_3").isNotNull(), 1).otherwise(0)),
    ).withColumn(
        "APP_EXT_SOURCES_PROD",
        F.col("EXT_SOURCE_1") * F.col("EXT_SOURCE_2") * F.col("EXT_SOURCE_3"),
    ).withColumn(
        "APP_EXT_SOURCE_1_TO_2_RATIO",
        safe_divide(F.col("EXT_SOURCE_1"), F.col("EXT_SOURCE_2")),
    ).withColumn(
        "APP_EXT_SOURCE_2_TO_3_RATIO",
        safe_divide(F.col("EXT_SOURCE_2"), F.col("EXT_SOURCE_3")),
    )

    # Clean any potential NaN generated by composite calculations
    for c in [
        "APP_EXT_SOURCES_MEAN",
        "APP_EXT_SOURCES_PROD",
        "APP_EXT_SOURCE_1_TO_2_RATIO",
        "APP_EXT_SOURCE_2_TO_3_RATIO",
    ]:
        df = df.withColumn(c, F.when(F.isnan(F.col(c)), None).otherwise(F.col(c)))

    # Document count flag sum
    doc_cols = [c for c in df.columns if c.startswith("FLAG_DOCUMENT_")]
    if doc_cols:
        doc_sum = F.lit(0)
        for dc in doc_cols:
            doc_sum = doc_sum + F.coalesce(F.col(dc), F.lit(0))
        df = df.withColumn("APP_DOCUMENT_FLAGS_COUNT", doc_sum)

    return df


