def build_gold_all(spark: SparkSession | None = None) -> dict[str, Any]:
    """Execute complete Gold aggregation and multi-table assembly pipeline."""
    should_stop_spark = False
    if spark is None:
        spark = get_spark("LoanDefaultPrediction-GoldAggregation-All")
        should_stop_spark = True

    timings: dict[str, float] = {}
    stage_start = time.time()
    total_start = stage_start

    GOLD_BASE_DIR.mkdir(parents=True, exist_ok=True)
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)

    try:
        # --------------------------------------------------------------
        # Stage 1: Bureau Balance Aggregation -> data/gold/bureau_balance
        # --------------------------------------------------------------
        logger.info("Stage 1/7: Aggregating bureau_balance...")
        print("[1/7] Aggregating bureau_balance (27.3M rows -> SK_ID_BUREAU) ...", flush=True)
        t0 = time.time()
        df_bb = spark.read.parquet(str(get_silver_dir("bureau_balance")))
        df_bb_agg = aggregate_bureau_balance(df_bb)
        bb_path = str(get_gold_dir("bureau_balance"))
        df_bb_agg.write.mode("overwrite").parquet(bb_path)
        df_bb_agg = spark.read.parquet(bb_path)  # Reload to break execution graph
        timings["bureau_balance_aggregation"] = round(time.time() - t0, 2)
        print(f"       -> PASS: {df_bb_agg.count():,} bureau records in {timings['bureau_balance_aggregation']}s", flush=True)

        # --------------------------------------------------------------
        # Stage 2: Bureau Aggregation -> data/gold/bureau
        # --------------------------------------------------------------
        logger.info("Stage 2/7: Aggregating bureau + bureau_balance -> SK_ID_CURR...")
        print("[2/7] Aggregating bureau + bureau_balance (1.7M rows -> SK_ID_CURR) ...", flush=True)
        t0 = time.time()
        df_bureau = spark.read.parquet(str(get_silver_dir("bureau")))
        df_bureau_agg = aggregate_bureau(df_bureau, df_bb_agg)
        bureau_path = str(get_gold_dir("bureau"))
        df_bureau_agg.write.mode("overwrite").parquet(bureau_path)
        df_bureau_agg = spark.read.parquet(bureau_path)
        timings["bureau_aggregation"] = round(time.time() - t0, 2)
        print(f"       -> PASS: {df_bureau_agg.count():,} applicants in {timings['bureau_aggregation']}s", flush=True)

        # --------------------------------------------------------------
        # Stage 3: Previous Application Aggregation -> data/gold/previous_application
        # --------------------------------------------------------------
        logger.info("Stage 3/7: Aggregating previous_application -> SK_ID_CURR...")
        print("[3/7] Aggregating previous_application (1.67M rows -> SK_ID_CURR) ...", flush=True)
        t0 = time.time()
        df_prev = spark.read.parquet(str(get_silver_dir("previous_application")))
        df_prev_agg = aggregate_previous_application(df_prev)
        prev_path = str(get_gold_dir("previous_application"))
        df_prev_agg.write.mode("overwrite").parquet(prev_path)
        df_prev_agg = spark.read.parquet(prev_path)
        timings["previous_application_aggregation"] = round(time.time() - t0, 2)
        print(f"       -> PASS: {df_prev_agg.count():,} applicants in {timings['previous_application_aggregation']}s", flush=True)

        # --------------------------------------------------------------
        # Stage 4: Installments Aggregation -> data/gold/installments
        # --------------------------------------------------------------
        logger.info("Stage 4/7: Aggregating installments_payments -> SK_ID_CURR...")
        print("[4/7] Aggregating installments_payments (13.6M rows -> SK_ID_CURR) ...", flush=True)
        t0 = time.time()
        df_inst = spark.read.parquet(str(get_silver_dir("installments_payments")))
        df_inst_agg = aggregate_installments(df_inst)
        inst_path = str(get_gold_dir("installments"))
        df_inst_agg.write.mode("overwrite").parquet(inst_path)
        df_inst_agg = spark.read.parquet(inst_path)
        timings["installments_aggregation"] = round(time.time() - t0, 2)
        print(f"       -> PASS: {df_inst_agg.count():,} applicants in {timings['installments_aggregation']}s", flush=True)

        # --------------------------------------------------------------
        # Stage 5: Credit Card Aggregation -> data/gold/credit_card
        # --------------------------------------------------------------
        logger.info("Stage 5/7: Aggregating credit_card_balance -> SK_ID_CURR...")
        print("[5/7] Aggregating credit_card_balance (3.8M rows -> SK_ID_CURR) ...", flush=True)
        t0 = time.time()
        df_cc = spark.read.parquet(str(get_silver_dir("credit_card_balance")))
        df_cc_agg = aggregate_credit_card(df_cc)
        cc_path = str(get_gold_dir("credit_card"))
        df_cc_agg.write.mode("overwrite").parquet(cc_path)
        df_cc_agg = spark.read.parquet(cc_path)
        timings["credit_card_aggregation"] = round(time.time() - t0, 2)
        print(f"       -> PASS: {df_cc_agg.count():,} applicants in {timings['credit_card_aggregation']}s", flush=True)

        # --------------------------------------------------------------
        # Stage 6: POS CASH Aggregation -> data/gold/pos_cash
        # --------------------------------------------------------------
        logger.info("Stage 6/7: Aggregating POS_CASH_balance -> SK_ID_CURR...")
        print("[6/7] Aggregating POS_CASH_balance (10.0M rows -> SK_ID_CURR) ...", flush=True)
        t0 = time.time()
        df_pos = spark.read.parquet(str(get_silver_dir("POS_CASH_balance")))
        df_pos_agg = aggregate_pos_cash(df_pos)
        pos_path = str(get_gold_dir("pos_cash"))
        df_pos_agg.write.mode("overwrite").parquet(pos_path)
        df_pos_agg = spark.read.parquet(pos_path)
        timings["pos_cash_aggregation"] = round(time.time() - t0, 2)
        print(f"       -> PASS: {df_pos_agg.count():,} applicants in {timings['pos_cash_aggregation']}s", flush=True)

        # --------------------------------------------------------------
        # Stage 7: Assemble Model Input Datasets
        # --------------------------------------------------------------
        logger.info("Stage 7/7: Assembling final Gold model input datasets...")
        print("[7/7] Assembling final Gold model input datasets (Left Join onto Spine) ...", flush=True)
        t0 = time.time()

        feature_tables = [
            ("bureau_features", df_bureau_agg),
            ("previous_application_features", df_prev_agg),
            ("installments_features", df_inst_agg),
            ("credit_card_features", df_cc_agg),
            ("pos_cash_features", df_pos_agg),
        ]

        # 7a. Train assembly
        df_train_silver = spark.read.parquet(str(get_silver_dir("application_train")))
        df_train_spine = build_app_features(df_train_silver, is_train=True)
        df_train_gold, train_join_audit = join_features_to_spine(
            df_train_spine, feature_tables, spine_name="application_train"
        )
        train_gold_path = str(get_gold_dir("model_input"))
        df_train_gold.write.mode("overwrite").parquet(train_gold_path)
        df_train_gold = spark.read.parquet(train_gold_path)

        # Validate training Gold
        is_train_valid, train_val_errors = validate_gold_df(
            df_train_gold, expected_rows=SPINE_TRAIN_ROWS, is_train=True
        )
        if not is_train_valid:
            raise AssertionError(f"Training Gold validation failed: {train_val_errors}")

        # 7b. Test assembly (inference dataset)
        df_test_silver = spark.read.parquet(str(get_silver_dir("application_test")))
        df_test_spine = build_app_features(df_test_silver, is_train=False)
        df_test_gold, test_join_audit = join_features_to_spine(
            df_test_spine, feature_tables, spine_name="application_test"
        )
        test_gold_path = str(get_gold_dir("model_input_test"))
        df_test_gold.write.mode("overwrite").parquet(test_gold_path)
        df_test_gold = spark.read.parquet(test_gold_path)

        # Validate test Gold
        is_test_valid, test_val_errors = validate_gold_df(
            df_test_gold, expected_rows=SPINE_TEST_ROWS, is_train=False
        )
        if not is_test_valid:
            raise AssertionError(f"Test Gold validation failed: {test_val_errors}")

        timings["final_application_joins"] = round(time.time() - t0, 2)
        timings["complete_gold_pipeline"] = round(time.time() - total_start, 2)

        print(
            f"       -> PASS: Training Model Input: {df_train_gold.count():,} rows | {len(df_train_gold.columns)} cols\n"
            f"       -> PASS: Test Model Input: {df_test_gold.count():,} rows | {len(df_test_gold.columns)} cols\n"
            f"       -> Completed in {timings['final_application_joins']}s",
            flush=True,
        )

        # --------------------------------------------------------------
        # Reports & Metadata
        # --------------------------------------------------------------
        all_join_audits = train_join_audit + test_join_audit

        # 1. Capture Physical Plan
        plan_path = REPORTS_DIR / "physical_plan.txt"
        with open(plan_path, "w", encoding="utf-8") as f:
            f.write("=== PHYSICAL EXECUTION PLAN: GOLD MODEL INPUT ASSEMBLY ===\n\n")
            f.write(df_train_gold._jdf.queryExecution().executedPlan().toString())
        logger.info(f"Captured physical plan: {plan_path}")

        # 2. Join Audit JSON
        join_audit_path = REPORTS_DIR / "join_audit.json"
        with open(join_audit_path, "w", encoding="utf-8") as f:
            json.dump(all_join_audits, f, indent=2)
        logger.info(f"Written join audit JSON: {join_audit_path}")

        # 3. Feature Registry YAML
        feature_registry = generate_feature_registry(df_train_gold)
        features_yaml_path = CONFIGS_DIR / "features.yaml"
        import yaml
        with open(features_yaml_path, "w", encoding="utf-8") as f:
            yaml.dump(feature_registry, f, sort_keys=False, indent=2)
        logger.info(f"Written feature registry YAML: {features_yaml_path}")

        # Measure directory sizes
        def get_dir_size_mb(path: pathlib.Path) -> float:
            total = sum(f.stat().st_size for f in path.glob("*.parquet") if f.is_file())
            return round(total / (1024 * 1024), 2)

        summary_data: dict[str, Any] = {
            "project": "Loan Default Prediction Using Big Data Analytics",
            "phase": "Phase 4 — Gold Aggregation & Multi-Table Assembly",
            "timestamp": datetime.now(timezone.utc).isoformat(),
            "train_rows": SPINE_TRAIN_ROWS,
            "train_cols": len(df_train_gold.columns),
            "test_rows": SPINE_TEST_ROWS,
            "test_cols": len(df_test_gold.columns),
            "train_size_mb": get_dir_size_mb(get_gold_dir("model_input")),
            "test_size_mb": get_dir_size_mb(get_gold_dir("model_input_test")),
            "total_runtime_seconds": timings["complete_gold_pipeline"],
            "stage_timings": timings,
            "join_audits": all_join_audits,
            "all_passed": True,
        }

        # 4. Gold Summary Markdown
        write_gold_summary_markdown(summary_data, df_train_gold)

        return summary_data

    finally:
        if should_stop_spark:
            spark.stop()


