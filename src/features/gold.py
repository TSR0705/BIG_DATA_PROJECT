def aggregate_installments(df_inst: DataFrame) -> DataFrame:
    """Aggregate installments_payments table to SK_ID_CURR grain.

    Preserves multi-record observations per installment, calculating payment behavior,
    delays (DAYS_ENTRY_PAYMENT - DAYS_INSTALMENT), and shortfalls (AMT_INSTALMENT - AMT_PAYMENT).
    """
    df_calc = df_inst.withColumn(
        "_DELAY",
        F.col("DAYS_ENTRY_PAYMENT") - F.col("DAYS_INSTALMENT"),
    ).withColumn(
        "_SHORTFALL",
        F.col("AMT_INSTALMENT") - F.col("AMT_PAYMENT"),
    ).withColumn(
        "_IS_LATE",
        F.when(F.col("_DELAY") > 0, 1).otherwise(0),
    ).withColumn(
        "_IS_UNDERPAID",
        F.when(F.col("_SHORTFALL") > 0, 1).otherwise(0),
    )

    return df_calc.groupBy("SK_ID_CURR").agg(
        F.count("*").alias("INST_RECORD_COUNT"),
        F.sum("AMT_INSTALMENT").alias("INST_AMT_INSTALMENT_SUM"),
        F.sum("AMT_PAYMENT").alias("INST_AMT_PAYMENT_SUM"),
        F.mean("AMT_PAYMENT").alias("INST_AMT_PAYMENT_MEAN"),
        F.max("AMT_PAYMENT").alias("INST_AMT_PAYMENT_MAX"),
        F.sum("_SHORTFALL").alias("INST_AMT_SHORTFALL_SUM"),
        F.mean("_DELAY").alias("INST_DELAY_MEAN"),
        F.max("_DELAY").alias("INST_DELAY_MAX"),
        F.min("_DELAY").alias("INST_DELAY_MIN"),
        F.sum("_IS_LATE").alias("INST_LATE_COUNT"),
        F.sum("_IS_UNDERPAID").alias("INST_UNDERPAID_COUNT"),
        F.max("DAYS_ENTRY_PAYMENT").alias("INST_DAYS_ENTRY_PAYMENT_MAX"),
        F.max("NUM_INSTALMENT_VERSION").alias("INST_NUM_INSTALMENT_VERSION_MAX"),
    ).withColumn(
        "INST_PAYMENT_RATIO",
        safe_divide(F.col("INST_AMT_PAYMENT_SUM"), F.col("INST_AMT_INSTALMENT_SUM")),
    ).withColumn(
        "INST_LATE_RATE",
        safe_divide(F.col("INST_LATE_COUNT"), F.col("INST_RECORD_COUNT")),
    ).withColumn(
        "INST_UNDERPAID_RATE",
        safe_divide(F.col("INST_UNDERPAID_COUNT"), F.col("INST_RECORD_COUNT")),
    )


