        F.mean("AMT_CREDIT").alias("PREV_AMT_CREDIT_MEAN"),
        F.max("AMT_CREDIT").alias("PREV_AMT_CREDIT_MAX"),
        F.sum("AMT_APPLICATION").alias("PREV_AMT_APPLICATION_SUM"),
        F.mean("AMT_APPLICATION").alias("PREV_AMT_APPLICATION_MEAN"),
